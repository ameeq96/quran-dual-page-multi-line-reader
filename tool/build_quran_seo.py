def render_sitemap(chapters: list[dict]) -> str:
    urls = [SITE + "/"] + [surah_url(chapter) for chapter in chapters]
    require(len(urls) == 115 and len(set(urls)) == 115, "Expected 115 unique canonical sitemap URLs")
    body = "\n".join(f"  <url><loc>{escaped(url)}</loc></url>" for url in urls)
    content = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- {MARKER} -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
{body}
</urlset>
'''
    require(len(ET.fromstring(content)) == 115, "Invalid sitemap output")
    return content


def safe_output(root: Path, relative: str) -> Path:
    web_root = root / "web"
    target = root / relative
    require(target.is_relative_to(web_root), "Output is outside the approved web directory")
    require(web_root.resolve().is_relative_to(root), "Resolved web directory escapes the project root")
    for candidate in [target, *target.parents]:
        require(not candidate.is_symlink(), f"Refusing symlink output path: {candidate}")
        if candidate == root:
            break
    require(target.resolve().is_relative_to(web_root.resolve()), "Resolved output escapes web directory")
    if target.exists():
        require(target.is_file(), f"Output is not a regular file: {target}")
        require(MARKER in target.read_text(encoding="utf-8"), f"Refusing to overwrite unrelated file: {target}")
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true", help="Validate inputs and compare existing generated outputs without writing")
    args = parser.parse_args()
    root = args.project_root.resolve()
    chapters, verses, copyright_block, summary = load_content(root)
    outputs = {
        f"web/surah/{chapter['slug']}/index.html": render_surah(chapter, chapters, verses, copyright_block).encode("utf-8")
        for chapter in chapters
    }
    outputs["web/robots.txt"] = f"# {MARKER}\nUser-agent: *\nAllow: /\n\nSitemap: {SITE}/sitemap.xml\n".encode("utf-8")
    outputs["web/sitemap.xml"] = render_sitemap(chapters).encode("utf-8")
    targets = {relative: safe_output(root, relative) for relative in outputs}
    differences = [relative for relative, data in outputs.items() if not targets[relative].exists() or targets[relative].read_bytes() != data]
    if args.check:
        require(not differences, "Generated outputs are missing or outdated: " + ", ".join(differences))
    else:
        for relative in differences:
            target = targets[relative]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(outputs[relative])
    summary.update({
        "mode": "check" if args.check else "build", "outputFiles": len(outputs),
        "changedFiles": 0 if args.check else len(differences), "sitemapUrls": len(chapters) + 1,
        "outputBytes": sum(map(len, outputs.values())),
        "outputSha256": hashlib.sha256(b"".join(
            relative.encode("utf-8") + b"\0" + outputs[relative] for relative in sorted(outputs)
        )).hexdigest(),
    })
    print(json.dumps(summary, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (ValueError, KeyError, IndexError, OSError) as error:
        print(f"Quran SEO build failed: {error}", file=sys.stderr)
        raise SystemExit(1)
