import 'package:flutter/material.dart';

import 'reader_localization.dart';

String prayerText(
  BuildContext context,
  String source, {
  Map<String, Object?> args = const {},
}) {
  final language = ReaderLocalizationScope.of(context).language;
  final translations = _prayerTranslations[source];
  final text = switch (language) {
    ReaderLanguage.urdu => translations?.$1 ?? source,
    ReaderLanguage.arabic => translations?.$2 ?? source,
    _ => source,
  };
  return text.replaceAllMapped(
    RegExp(r'\{([^{}]+)\}'),
    (match) => args.containsKey(match[1]) ? '${args[match[1]]}' : match[0]!,
  );
}

