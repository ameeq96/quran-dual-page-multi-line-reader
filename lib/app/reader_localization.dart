enum ReaderLanguage { english, urdu, romanUrdu, arabic }

extension ReaderLanguageLabel on ReaderLanguage {
  String get label => switch (this) {
        ReaderLanguage.english => 'English',
        ReaderLanguage.urdu => 'اردو',
        ReaderLanguage.romanUrdu => 'Roman Urdu',
        ReaderLanguage.arabic => 'العربية',
      };
}

class ReaderLocalization extends ChangeNotifier {
  ReaderLocalization({SharedPreferences? preferences})
      : _injectedPreferences = preferences;

  static final ReaderLocalization instance = ReaderLocalization();
  static const storageKey = 'reader_interface_language_v1';

  final SharedPreferences? _injectedPreferences;
  Future<SharedPreferences>? _preferencesFuture;
  Future<SharedPreferences> get _preferences => _preferencesFuture ??=
      _injectedPreferences == null
          ? SharedPreferences.getInstance()
          : Future.value(_injectedPreferences);
  Future<void>? _loading;
  String _profileId = 'default';
  String get _storageKey => ReaderProfileStore.keyFor(storageKey, _profileId);
  Future<void> loadForProfile(String profileId) async {
    if (_profileId == profileId) return load();
    _profileId = profileId;
    _loading = null;
    await load();
  }
  ReaderLanguage _language = ReaderLanguage.english;

  ReaderLanguage get language => _language;
  Locale get locale => Locale(switch (_language) {
        ReaderLanguage.urdu => 'ur',
        ReaderLanguage.arabic => 'ar',
        _ => 'en',
      });
  TextDirection get textDirection =>
      _language == ReaderLanguage.urdu || _language == ReaderLanguage.arabic
      ? TextDirection.rtl
      : TextDirection.ltr;

  Future<void> load() => _loading ??= _load();

  Future<void> _load() async {
    final profileId = _profileId;
    final key = _storageKey;
    try {
      final saved = (await _preferences).getString(key);
      if (_profileId != profileId) return;
      _language = ReaderLanguage.values.firstWhere(
        (language) => language.name == saved,
        orElse: () => ReaderLanguage.english,
      );
      notifyListeners();
    } catch (_) {
      // A storage failure must not prevent the Quran reader from opening.
    }
  }

  Future<void> setLanguage(ReaderLanguage language) async {
    await load();
    if (_language == language) return;
    final profileId = _profileId;
    final key = _storageKey;
    final saved = await (await _preferences).setString(key, language.name);
    if (!saved) throw StateError('Unable to save interface language.');
    if (_profileId != profileId) return;
    _language = language;
    notifyListeners();
  }

  String translate(String source, {Map<String, Object?> args = const {}}) {
    final english = _format(source, args);
    if (_language == ReaderLanguage.english) return english;
    final directKey = _allTranslations.containsKey(source) ? source : english;
    final direct = _allTranslations[directKey];
    if (direct != null) return _format(_select(directKey, direct), args);
    if (!RegExp('[A-Za-z]').hasMatch(english)) return english;
    for (final template in _templates) {
      final match = template.pattern.firstMatch(english);
      if (match == null) continue;
      final values = <String, Object?>{
        for (var i = 0; i < template.names.length; i++)
          template.names[i]: match.group(i + 1),
      };
      return _format(_select(template.source, template.translation), values);
    }
    return english;
  }

  String _select(String source, (String, String) value) => switch (_language) {
        ReaderLanguage.arabic => readerArabicTranslations[source] ?? source,
        ReaderLanguage.urdu => value.$1,
        _ => value.$2,
      };

  static String _format(String value, Map<String, Object?> args) =>
      value.replaceAllMapped(RegExp(r'\{([^{}]+)\}'),
          (match) => args.containsKey(match[1]) ? '${args[match[1]]}' : match[0]!);
}

class ReaderLocalizationScope extends InheritedNotifier<ReaderLocalization> {
  const ReaderLocalizationScope({
    super.key,
    required ReaderLocalization localization,
    required super.child,
  }) : super(notifier: localization);

  static ReaderLocalization of(BuildContext context) => context
          .dependOnInheritedWidgetOfExactType<ReaderLocalizationScope>()
          ?.notifier ??
      ReaderLocalization.instance;
}

String tr(BuildContext context, String source,
        {Map<String, Object?> args = const {}}) =>
    ReaderLocalizationScope.of(context).translate(source, args: args);

class _TranslationTemplate {
  _TranslationTemplate(this.source, this.translation) {
    final placeholders = RegExp(r'\{([^{}]+)\}').allMatches(source).toList();
    names = placeholders.map((match) => match[1]!).toList();
    var offset = 0;
    final patternText = StringBuffer('^');
    for (final match in placeholders) {
      patternText.write(RegExp.escape(source.substring(offset, match.start)));
      patternText.write(source == 'P{0}' || source == 'L{0}'
          ? r'(\d+)'
          : r'([\s\S]+?)');
      offset = match.end;
    }
    patternText.write(RegExp.escape(source.substring(offset)));
    patternText.write(r'$');
    pattern = RegExp(patternText.toString());
  }

  final String source;
  final (String, String) translation;
  late final RegExp pattern;
  late final List<String> names;
}

